'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('score-key-transposer.html','utf8'),c=vm.createContext({});
vm.runInContext(html.slice(html.indexOf('// Score music functions:'),html.indexOf('// End score music functions.')),c);
const dictionary=c.scoreRecognizerDictionary('C\nm\n7\n');
const steps=[1,1,0,1,2,2,3],classes=dictionary.length,data=new Float32Array(steps.length*classes);
for(const [step,index] of steps.entries())data[step*classes+index]=.9;
const decoded=c.decodeScoreRecognizer({dims:[1,steps.length,classes],data},dictionary);
assert.equal(decoded.text,'CCm7','CTC blanks separate repeats; repeated frames collapse');
assert(Math.abs(decoded.confidence-90)<.001);
assert.throws(()=>c.decodeScoreRecognizer({dims:[1,1,3],data},dictionary),/dictionary/);
const input=c.scoreRecognizerInput({width:2,height:2,data:new Uint8ClampedArray(16).fill(255)});
assert.deepEqual(Array.from(input.dims),[1,3,48,48]);assert(input.data.every(value=>value===1));
for(const [raw,text] of [['C(SUS4)','C(SUS4)'],['cadd2','Cadd2'],['Cm7','Cm7'],['CM7','CM7'],['F/c','F/C'],['B♭/F♯','Bb/F#'],['Fa7',null],['C2E',null],['noise',null]])assert.equal(c.normalizeScoreRecognizer(raw),text);
const reading=(text,confidence,support=1,styles=['gray'])=>({text,confidence,support,styles});
const select=(primary,secondary=[])=>c.selectScoreRegionReading(primary,secondary)?.text;
assert.equal(select([reading('C',99),reading('C7',80)]),'C','Length alone must not beat confidence');
assert.equal(select([reading('F/C',99)],[reading('F/C#',0,3,['gray','binary'])]),'F/C#','Extra symbol requires several actual readings');
assert.equal(select([reading('F/C',99)],[reading('F/C#',95,2,['gray'])]),'F/C','Two PSMs on one crop do not suffice');
assert.equal(select([reading('DSUS4',98)],[reading('Dsus4',90,4,['gray','flat'])]),'Dsus4');
assert.equal(select([reading('CM7',98)],[reading('Cm7',99,4,['gray','flat'])]),'CM7','Minor/major is not keyword case');
assert.equal(select([],[reading('Gm7',0,3,['gray','binary'])]),'Gm7');
console.log('Region recognizer: tensor layout, CTC, model/dictionary validation, literal notation and cross-engine evidence passed.');
